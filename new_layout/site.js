function bindInteractions() {
  const toggle = document.querySelector("[data-mobile-toggle]");
  const nav = document.querySelector("[data-mobile-nav]");
  if (toggle && nav) {
    toggle.addEventListener("click", () => {
      nav.classList.toggle("is-open");
    });
  }

  const form = document.querySelector("[data-prototype-form]");
  const message = document.querySelector("[data-form-message]");
  if (form && message) {
    form.addEventListener("submit", (event) => {
      event.preventDefault();
      message.textContent = "Prototype only: this shows the new layout. The existing React contact workflow can be wired into this structure next.";
      message.style.color = "#6f2ea8";
    });
  }
}

function boot() {
  const pageKey = document.body.dataset.page || "home";
  const root = document.getElementById("app");
  if (!root) return;
  document.title = (pageMeta[pageKey] || pageMeta.home).title;
  root.innerHTML = renderPage(pageKey);
  bindInteractions();
}

document.addEventListener("DOMContentLoaded", boot);
